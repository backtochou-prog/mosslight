"""Hand-authored 16x16 item icons (pilot collection).

Each icon is a pixel grid: one character per pixel, '.' = transparent, with a
legend mapping characters to (palette family, rank). Light from the upper-
left; outlines are the material's own dark colour, never black. Edit the grid
to edit the art — this file IS the artwork.
"""
ICONS = {}
def icon(id, legend, rows):
    rows = [r for r in rows.strip('\n').split('\n')]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), (id, [len(r) for r in rows])
    ICONS[id] = (legend, rows)

