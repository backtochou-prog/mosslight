def _rod(id, shaft, grip, leg, tip, wraps):
    rows = ["................" for _ in range(16)]
    rows = [list(r) for r in rows]
    for k in range(13):
        x, y = 1 + k, 14 - k
        rows[y][x] = 'H' if k >= 0 else 'H'
        if x + 1 < 15: rows[y][x + 1] = 'd'
        if y + 1 < 16 and k < 5: rows[y + 1][x] = 'o'
    for k in range(4):
        rows[14 - k][1 + k] = 'G'; rows[15 - k][1 + k] = 'g'
    for k in wraps: rows[14 - k][1 + k] = 'W'
    for y, x, ch in tip: rows[y][min(x, 14)] = ch
    icon(id, dict(leg, H=shaft[0], d=shaft[1], o=shaft[2], G=grip[0], g=grip[1]), "\n".join("".join(r) for r in rows))
