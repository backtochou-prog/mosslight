"""Fish collection report: can every species actually be caught in the game as it runs?

Checks each species against what really happens: the weather planner (Survival.Weather: fog only before 10:00,
snow only in winter, no rain in winter), the clock phases, rod tiers that can be crafted, and baits whose ingredients
the player can obtain (and how: gathered, crafted, or only through a neighbour). Writes docs/FISH_REPORT.md.
Run: python3 tools/fish_report.py
"""
import json, os
from collections import Counter, defaultdict
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda p: json.load(open(os.path.join(ROOT, p)))
F = J('assets/fishing/fishing.json'); NODES = J('assets/items/nodes.json')['nodes']; RECIPES = J('assets/build/recipes.json')['recipes']
gathered = {d for n in NODES for d, lo, hi in n['drops'] if hi > 0}
gathered |= {'minnow'}                                              # a common pond fish, caught on worms
social_only = set()                                                 # items only a neighbour can give (none since Prompt 16 pass 2)
def source(item):
    if item in gathered: return 'gathered'
    rs = [r for r in RECIPES if r['result'] == item]
    if rs:
        srcs = [max((source(k) for k in r['ingredients']), key=lambda s: ['gathered', 'crafted', 'neighbour', 'none'].index(s)) for r in rs]
        best = min(srcs, key=lambda s: ['gathered', 'crafted', 'neighbour', 'none'].index(s)); return 'crafted' if best == 'gathered' else best
    return 'neighbour' if item in social_only else 'none'
BAIT_ITEM = {b['kind']: b['id'] for b in F['tackle']['baits'] if b.get('kind')}
bait_src = {k: source(v) for k, v in BAIT_ITEM.items()}
# weather that the planner can produce per season, and the periods each can cover
ODDS = {'spring': ['clear', 'light_rain', 'heavy_rain', 'fog', 'wind'], 'summer': ['clear', 'light_rain', 'heavy_rain', 'fog', 'wind'], 'autumn': ['clear', 'light_rain', 'heavy_rain', 'fog', 'wind'], 'winter': ['clear', 'snow', 'fog', 'wind']}
FOG_PERIODS = {'deep', 'dawn', 'day'}                                # blocks 0-6 and 6-10; plus evening mist (20-24) in spring and autumn
def weather_ok(f, season, period):
    for k in f['weather']:
        if k == 'any': return True
        if k in ('rain', 'after_rain') and season != 'winter': return True
        if k == 'fog' and 'fog' in ODDS[season] and (period in FOG_PERIODS or (season in ('spring', 'autumn') and period in ('night', 'deep'))): return True
        if k == 'snow' and season == 'winter': return True
        if k in ('clear', 'wind') and k in ODDS[season]: return True
    return False
rows = []; impossible = []; neighbour_only = []
for f in F['fish']:
    seasons = ['spring', 'summer', 'autumn', 'winter'] if 'any' in f['seasons'] else f['seasons']; periods = ['dawn', 'day', 'dusk', 'night', 'deep'] if 'any' in f['periods'] else f['periods']
    ok_cond = [(s, p) for s in seasons for p in periods if weather_ok(f, s, p)]
    tier = F['rarity'][f['rarity']]['tier']
    baits = [(b, bait_src.get(b, 'none')) for b in f['bait']]
    usable = [b for b, s in baits if s in ('gathered', 'crafted')]
    if f['rarity'] == 'common' and not usable: usable = ['bare hook']             # commons take a bare hook at a lower rate
    if not ok_cond: impossible.append((f['id'], 'no season/period/weather the game produces'))
    elif not usable and not any(s == 'neighbour' for b, s in baits): impossible.append((f['id'], 'no bait the player can get: ' + ', '.join(f['bait'])))
    elif not usable: neighbour_only.append(f['id'])
    rows.append((f['id'], f['habitat'], f['rarity'], tier, len(ok_cond), ','.join(usable) or '-', f.get('event') or ''))
lines = ['# Fish collection report', '', 'Generated by `tools/fish_report.py` against the weather planner, clock, craftable rods and obtainable baits.', '',
         f"- species: {len(F['fish'])}; by rarity: {dict(Counter(f['rarity'] for f in F['fish']))}",
         f"- bait sources: {bait_src}",
         f"- catchable with gathered or crafted bait: {len(F['fish']) - len(impossible) - len(neighbour_only)}",
         f"- only with neighbour-given bait: {neighbour_only or 'none'}",
         f"- impossible: {impossible or 'none'}", '',
         '| fish | water | rarity | rod tier | season×period windows | baits that work | festival |', '|---|---|---|---|---|---|---|']
lines += [f'| {a} | {b} | {c} | {d} | {e} | {g} | {h} |' for a, b, c, d, e, g, h in rows]
open(os.path.join(ROOT, 'docs', 'FISH_REPORT.md'), 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines[:9]))
