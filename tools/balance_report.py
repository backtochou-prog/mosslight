"""Balance report: reads the built game data and measures the economy the player actually lives in.

For every raw material: how much the clearing supplies per day (expected value over node yields and respawns,
day-only vs night), and which nodes never come back. For each home stage (Tent -> Basic Shelter -> Cabin ->
Reinforced Home -> Fortified Estate): the reference build expanded down to raw materials, the energy and game
minutes it costs, and how many in-game days the scarcest material makes you wait. Also flags progression that
hangs on finite or very rare sources, and tools that can break with no way back.

Run:  python3 tools/balance_report.py            (prints, and writes docs/BALANCE_REPORT.md)
"""
import json, math, os, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda p: json.load(open(os.path.join(ROOT, p)))
ITEMS = {i['id']: i for i in J('assets/items/items.json')['items']}
NODES = J('assets/items/nodes.json')['nodes']
TOOLS = {t['id']: t for t in J('assets/items/tools.json')['tools']}
RECIPES = J('assets/build/recipes.json')['recipes']
CO = J('assets/build/components.json'); COMP = {c['id']: c for c in CO['components']}
SURV = J('assets/survival/config.json'); ACT = dict(SURV['activities']); ACT.update(J('assets/items/nodes.json').get('activities_extra', {}))
MON = J('assets/monsters/monsters.json')

WEATHER_SHARE = {'rain': .22, 'after_rain': .3, 'clear': .5}      # share of hours each condition holds, from the weather planner (spring-autumn mean)

def supply():
    """expected units per day of each item, from nodes; also energy and minutes per unit"""
    out = defaultdict(lambda: {'per_day': 0.0, 'finite': 0.0, 'energy': [], 'nodes': []})
    for n in NODES:
        act = ACT.get(n['activity'], {'energy': 0, 'minutes': 0})
        share = 1.0
        if n.get('weather'):
            ws = n['weather'].split(','); share = min(1, sum(WEATHER_SHARE.get(w, 0) for w in ws)) or .2
        seasons = n.get('seasons'); sshare = (len(seasons.split(',')) / 4) if seasons else 1
        for id_, lo, hi in n['drops']:
            mean = (lo + hi) / 2 if lo > 0 else hi / 2 * .55          # optional extras: a 55% chance of the roll
            per_yield = mean
            if n.get('respawn_mode') == 'none' or not n.get('respawn_hours'):
                out[id_]['finite'] += per_yield * n['yields'] * share
            else:
                cycle_days = n['respawn_hours'] / 24 + .3              # a visit's worth of slack
                out[id_]['per_day'] += per_yield * n['yields'] / cycle_days * share * sshare
            out[id_]['energy'].append(act['energy'] / max(.01, per_yield)); out[id_]['nodes'].append(n['id'])
    return out

RAW = None
def expand(cost, mult=1, acc=None, energy=None, minutes=None):
    """expand a cost dict down to gathered raw materials through crafting recipes"""
    acc = acc if acc is not None else defaultdict(float); energy = energy if energy is not None else [0.0]; minutes = minutes if minutes is not None else [0.0]
    for k, q in cost.items():
        rs = [r for r in RECIPES if r['result'] == k and r['id'] not in ('charcoal', 'wire_drawn') and r['station'] in ('hand', 'workbench', 'stone_station', 'furnace', 'wood_station', 'adv_bench') and r['id'] != 'plank_fine']
        if rs and k not in RAW:
            r = rs[0]; times = q * mult / r['qty']; energy[0] += r['energy'] * times; minutes[0] += r['minutes'] * times
            expand(r['ingredients'], times, acc, energy, minutes)
        else: acc[k] += q * mult
    return acc, energy, minutes

def recipe_cost(rid): r = next(x for x in RECIPES if x['id'] == rid); return r

# reference homes, one per stage; each must stand on its own (walls of a closed room, a door, a roof, the furniture that makes the stage)
STAGES = [
  ('1 Tent (start)', {}, []),
  ('2 Basic shelter (3x3 room)', {'fnd_wood': 9, 'floor_plank': 9, 'wall_wood': 11, 'door': 1, 'roof_thatch': 9}, ['workbench', 'bed_rustic', 'crate']),
  ('3 Cabin (4x4, shingle roof)', {'fnd_reinforced': 16, 'floor_tile': 16, 'wall_cottage': 13, 'door_hinged': 1, 'window_pane': 2, 'roof_shingle': 16, 'torch_post': 2}, ['stone_station', 'wood_station', 'furnace', 'chest', 'table_rustic', 'chair_rustic', 'stove']),
  ('4 Reinforced home (4x4 stone, fenced yard)', {'fnd_stone': 16, 'floor_flag': 16, 'wall_stone': 11, 'wall_reinforced': 2, 'door_hinged': 1, 'window_nightglass': 2, 'roof_slate': 16, 'fence': 16, 'gate_reinforced': 1, 'torch_post': 2}, ['bed_cottage', 'bookshelf']),
  ('5 Fortified estate (metal walls, defences)', {'wall_metal': 15, 'spikes': 4, 'barricade': 2, 'watch_platform': 1, 'torch_post': 4}, ['adv_bench', 'chest_big']),
]

def main():
    global RAW
    S = supply(); RAW = (set(k for k in S) | {'coal', 'iron_ore', 'copper_ore'}) - {'bolt'}
    lines = ['# Balance report', '', 'Generated by `tools/balance_report.py` from the built data in `assets/`. Expected values; one player, one clearing.', '']
    lines += ['## Supply per day (expected, from resource nodes)', '', '| item | per day | finite total | energy per unit | from |', '|---|---|---|---|---|']
    for k in sorted(S, key=lambda k: -S[k]['per_day']):
        s = S[k]; lines.append(f"| {k} | {s['per_day']:.2f} | {s['finite']:.1f} | {min(s['energy']):.1f} | {', '.join(s['nodes'])} |")
    lines += ['', '## Home stages', '', '| stage | raw materials | energy | game hours | days (energy) | days (scarcest material) |', '|---|---|---|---|---|---|']
    total_raw = defaultdict(float); flags = []; day_energy = SURV['energy']['max'] * .85      # a day's usable energy, leaving room to walk home
    for name, parts, crafts in STAGES:
        cost = defaultdict(float); en = 0.0; mins = 0.0
        for cid, q in parts.items():
            c = COMP[cid]
            for k, v in c['cost'].items(): cost[k] += v * q
            en += c['energy'] * q; mins += c['minutes'] * q
        for rid in crafts:
            r = recipe_cost(rid)
            for k, v in r['ingredients'].items(): cost[k] += v
            en += r['energy']; mins += r['minutes']
        raw, e2, m2 = expand(cost)
        en += e2[0]; mins += m2[0]
        # gathering energy for the raw materials
        gen = 0.0; worst = (0, '')
        for k, q in raw.items():
            s = S.get(k)
            if not s or (s['per_day'] <= 0 and s['finite'] < q + total_raw[k]):
                flags.append(f"stage {name}: needs {q:.0f} {k}, which the clearing cannot supply ({'finite ' + format(s['finite'], '.1f') if s else 'no source'})"); continue
            gen += q * min(s['energy'])
            if s['per_day'] > 0:
                d = q / s['per_day']
                if d > worst[0]: worst = (d, k)
        en += gen; total_raw.update({k: total_raw[k] + v for k, v in raw.items()})
        rs = ', '.join(f"{k} {v:.0f}" for k, v in sorted(raw.items(), key=lambda kv: -kv[1]))
        lines.append(f"| {name} | {rs or '-'} | {en:.0f} | {mins / 60:.1f} | {en / day_energy:.1f} | {worst[0]:.1f} ({worst[1]}) |")
    # tools
    lines += ['', '## Tools', '']
    rec_results = {r['result'] for r in RECIPES} | {r.get('tool') for r in RECIPES if r.get('tool')}
    for t in TOOLS.values():
        mend = [r['id'] for r in RECIPES if r.get('tool') == t['id']]
        tiers = t.get('tiers') or []
        lines.append(f"- {t['name']}: durability {t['durability']}, efficiency {t['efficiency']}; tiers {[x['name'] for x in tiers] or 'none'}; mend/upgrade recipes: {mend or 'NONE'}")
        if t['durability'] and not mend: flags.append(f"tool {t['id']} breaks after {t['durability']} uses and nothing repairs or replaces it")
    # finite essentials
    essentials = {'iron_ore', 'coal', 'scrap_metal', 'clay', 'glass_shard', 'bolt', 'rusted_gear', 'nightglass', 'stone', 'log', 'fiber'}
    for k in sorted(essentials):
        s = S.get(k)
        if not s: flags.append(f"{k}: no gatherable source at all"); continue
        if s['per_day'] < .15: flags.append(f"{k}: only {s['per_day']:.2f}/day renewable (+{s['finite']:.1f} finite) - essential recipes use it")
    # night
    lines += ['', '## Night', '', f"- spawn budget by phase: {MON['phases']}", f"- player health {MON['player']['max_health']}, hits: " + ', '.join(f"{k} {c['damage']}" for k, c in MON['creatures'].items() if c['damage'])]
    lines += ['', '## Flags', ''] + ([f'- {f}' for f in flags] or ['- none'])
    txt = '\n'.join(lines) + '\n'
    os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True); open(os.path.join(ROOT, 'docs', 'BALANCE_REPORT.md'), 'w').write(txt)
    print(txt)
    return flags

if __name__ == '__main__':
    sys.exit(1 if main() and '--strict' in sys.argv else 0)
