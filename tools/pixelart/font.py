def build(out_png, out_json):
    import json
    import numpy as np
    from PIL import Image
    chars = list(G); x = 0; meta = {}; widths = [len(G[c][0]) for c in chars]; atlas = np.zeros((9, sum(widths) + len(chars)), np.uint8)
    for c in chars:
        w = len(G[c][0])
        for y, row in enumerate(G[c]):
            for i, ch in enumerate(row):
                if ch == '#': atlas[y, x + i] = 255
        meta[c] = [x, w]; x += w + 1
    Image.fromarray(atlas, 'L').save(out_png); json.dump(dict(height=9, baseline=7, spacing=1, space=3, glyphs=meta), open(out_json, 'w'), ensure_ascii=False)
    return len(chars)

def epx(b):
    import numpy as np
    h, w = b.shape; o = np.zeros((h * 2, w * 2), bool); P = np.pad(b, 1)
    for y in range(h):
        for x in range(w):
            c = b[y, x]; A = P[y, x + 1]; B = P[y + 1, x + 2]; C = P[y + 1, x]; D = P[y + 2, x + 1]
            o[2 * y, 2 * x] = A if (C == A and C != D and A != B) else c; o[2 * y, 2 * x + 1] = B if (A == B and A != C and B != D) else c
            o[2 * y + 1, 2 * x] = C if (D == C and D != B and C != A) else c; o[2 * y + 1, 2 * x + 1] = D if (B == D and B != A and D != C) else c
    return o
def build_heading(out_png, out_json):
    """The heading face: each glyph smoothed to 2x on its own, so letters never bleed into each other."""
    import json
    import numpy as np
    from PIL import Image
    chars = list(G); total = sum(len(G[c][0]) * 2 + 2 for c in chars); atlas = np.zeros((18, total), np.uint8); x = 0; meta = {}
    for c in chars:
        b = np.array([[ch == '#' for ch in row] for row in G[c]]); e = epx(b); w = e.shape[1]; atlas[:, x:x + w] = e * 255; meta[c] = [x, w]; x += w + 2
    Image.fromarray(atlas, 'L').save(out_png); json.dump(dict(height=18, baseline=14, spacing=2, space=6, glyphs=meta), open(out_json, 'w'), ensure_ascii=False)
